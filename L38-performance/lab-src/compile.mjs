// Writes src/gen/parts.compiled.tsx: src/parts.tsx after the real React Compiler (babel-plugin-react-compiler).
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\//, ""));
const require = createRequire(path.join(here, "package.json"));
const babel = require("@babel/core");
const compiler = require("babel-plugin-react-compiler");

mkdirSync(path.join(here, "src/gen"), { recursive: true });
for (const [from, to] of [["src/parts.tsx", "src/gen/parts.compiled.tsx"]]) {
  const source = readFileSync(path.join(here, from), "utf8");
  const events = [];
  const out = babel.transformSync(source, {
    filename: path.join(here, from),
    babelrc: false,
    configFile: false,
    parserOpts: { plugins: ["typescript", "jsx"] },
    plugins: [[compiler, { logger: { logEvent: (_f, e) => events.push(e) }, panicThreshold: "none" }]],
  });
  // the import of "./util" must still point at src/util.ts from src/gen/
  const code = out.code.replace(/from "\.\/util"/g, 'from "../util"');
  writeFileSync(path.join(here, to), "// GENERATED by compile.mjs from " + from + " with babel-plugin-react-compiler: do not edit\n" + code);
  const ok = events.filter((e) => e.kind === "CompileSuccess").map((e) => e.fnName);
  const bad = events.filter((e) => e.kind !== "CompileSuccess" && e.kind !== "Timing");
  console.log(to, "compiled:", ok.join(", "), bad.length ? "| NOT compiled: " + bad.length : "");
}
